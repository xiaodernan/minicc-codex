"""M8-T1160 — the drift sentinel: a model-free oracle for repo self-consistency.

The other admin tiles ask the model to read the workspace. This one asks the
machine two cheaper, harder questions that a model should never be trusted to
answer either:

1. is ``git HEAD`` the commit the published fact pack was cut from
   (``docs/latest.json``)? A mismatch means the showcase is not serving this
   revision yet — proof that the auto-sync pipeline is doing its job or not.
2. how many commits sit on top of the fact pack's head? The fact pack is
   generated by a workflow *after* its source commit, so one commit of lag is
   the normal post-push state — more means the pack is behind or this clone
   is ahead of the remote. A shallow clone that cannot see the pack's head
   object reports unknown, never red.
3. are the two CRLF-pinned files still byte-CRLF? A single LF byte in them is
   a broken promise the gates can't see until the next run.
4. does ``doc_pointers.py --check`` exit 0 right now? The repo's own
   documentation gate, run live, not remembered.

No LLM is consulted: this tile is the sentinel for the things the model
cannot verify. Every check degrades loudly instead of silently — a wire
failure is reported as a failure, never as a green check. Not memoized for
longer than 10 minutes; the panel never blocks on this and the operator can
``?fresh=1`` past the memo whenever they want the truth re-earned.
"""

from __future__ import annotations

import json
import subprocess
import sys
import threading
from pathlib import Path
from typing import Any

from .clock import utc_stamp
from .oracle_common import memo_read, memo_write

_DOC_MEMO_KEY = "admin-doc-pointers:v1"
_GIT_TIMEOUT_SECONDS = 10.0
_CHECK_TIMEOUT_SECONDS = 90.0

#: Names of in-flight background doc_pointers runs, so a burst of panel opens
#: does not spawn a check per request.
_doc_inflight = threading.Lock()
_doc_running = False


def _git_head(workspace: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(workspace),
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=_GIT_TIMEOUT_SECONDS,
            check=True,
        )
    except subprocess.TimeoutExpired as exc:
        raise RuntimeError(f"git rev-parse timed out after {_GIT_TIMEOUT_SECONDS}s") from exc
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError(f"git rev-parse failed: {exc}") from exc
    return out.stdout.decode("utf-8", errors="replace").strip()


def _pack_head_visible(workspace: Path, pack_head: str) -> bool:
    """True iff the pack's head object exists in this clone.

    A shallow checkout (actions/checkout@v4's default fetch-depth=1) carries only
    HEAD; the fact pack usually points at an ancestor object the clone does not
    have, so rev-list --count pack_head..HEAD simply has nothing to count.  That
    is not a red — the pack's provenance is outside what this clone can see.
    """
    try:
        out = subprocess.run(
            ["git", "cat-file", "-e", f"{pack_head}^{{commit}}"],
            cwd=str(workspace),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=_GIT_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return out.returncode == 0


def _commits_ahead(workspace: Path, pack_head: str) -> int | None:
    """How many commits sit on top of the fact pack's head, or None when invisible.

    The fact pack is written by a workflow that runs *after* the source
    commit lands, so HEAD is usually exactly one commit (the pack itself)
    ahead of pack.head. Zero means the pack describes HEAD itself; one is the
    normal post-push state; anything else means the pack is behind HEAD by
    more than its own commit — either the workflow has not run yet, or this
    clone holds commits the remote has not seen. When the pack's head object
    is not present in the clone (shallow checkout), the answer is unknowable,
    not wrong — call sites must render it as unknown.
    """
    if not _pack_head_visible(workspace, pack_head):
        return None
    try:
        out = subprocess.run(
            ["git", "rev-list", "--count", f"{pack_head}..HEAD"],
            cwd=str(workspace),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=_GIT_TIMEOUT_SECONDS,
            check=True,
        )
    except (OSError, subprocess.TimeoutExpired, subprocess.CalledProcessError):
        return None
    return int(out.stdout.decode("utf-8", errors="replace").strip() or 0)


def _fact_pack(workspace: Path) -> dict[str, Any]:
    path = workspace / "docs" / "latest.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    head = str(data.get("head") or "").strip()
    if not head:
        raise RuntimeError("docs/latest.json carries no head")
    return {
        "head": head,
        "total_commits": data.get("total_commits"),
        "roadmap_batches": data.get("roadmap_batches"),
        "tracked_files": data.get("tracked_files"),
        "test_files": data.get("test_files"),
        "roadmap_lines": data.get("roadmap_lines"),
        "generated_at": data.get("generated_at"),
    }


def _crlf_pin(path: Path) -> dict[str, Any]:
    raw = path.read_bytes()
    crlf = raw.count(b"\r\n")
    lf_only = raw.count(b"\n") - crlf
    return {"crlf": crlf, "lf_only": lf_only, "ok": crlf > 0 and lf_only == 0}


def _doc_pointers_sync(workspace: Path) -> dict[str, Any]:
    try:
        proc = subprocess.run(
            [sys.executable, "scripts/doc_pointers.py", "--check"],
            cwd=str(workspace),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=_CHECK_TIMEOUT_SECONDS,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return {"rc": 124, "ok": False, "tail": f"doc_pointers --check timed out after {_CHECK_TIMEOUT_SECONDS}s", "status": "run"}
    out = proc.stdout.decode("utf-8", errors="replace")
    lines = [line for line in out.splitlines() if line.strip()]
    tail = lines[-1][:400] if lines else ""
    return {"rc": int(proc.returncode), "ok": proc.returncode == 0, "tail": tail, "status": "run"}


def _spawn_doc_pointers(workspace: Path) -> bool:
    """Kick off one background check; returns True if this call spawned it."""
    global _doc_running
    with _doc_inflight:
        if _doc_running:
            return False
        _doc_running = True

    def run() -> None:
        global _doc_running
        try:
            result = _doc_pointers_sync(workspace)
            memo_write(_DOC_MEMO_KEY, result)
        except Exception as exc:  # noqa: BLE001 - background threads must not die silently
            memo_write(_DOC_MEMO_KEY, {"rc": None, "ok": False, "tail": f"{type(exc).__name__}: {exc}", "status": "error"})
        finally:
            with _doc_inflight:
                _doc_running = False

    thread = threading.Thread(target=run, name="drift-doc-pointers", daemon=True)
    thread.start()
    return True


def _doc_pointers(workspace: Path, *, force_refresh: bool = False) -> dict[str, Any]:
    """Never block the cheap checks on the expensive one.

    Default path: cached result if present, otherwise kick off a background
    check and report ``status="running"``. ``force_refresh`` first re-reads the
    cache (a background run may have landed), otherwise runs synchronously
    under the cap — that is what the panel's refresh button asks for.
    """
    cached = memo_read(_DOC_MEMO_KEY)
    if cached is not None:
        return {**cached, "status": "cached"}
    if force_refresh:
        result = _doc_pointers_sync(workspace)
        memo_write(_DOC_MEMO_KEY, result)
        return result
    _spawn_doc_pointers(workspace)
    return {"rc": None, "ok": None, "tail": "", "status": "running"}


def build_workspace_drift(workspace: Path, *, force_refresh: bool = False) -> dict[str, Any]:
    workspace = Path(workspace)
    try:
        head_live = _git_head(workspace)
        pack = _fact_pack(workspace)
        ahead = _commits_ahead(workspace, pack["head"])
        index_html = _crlf_pin(workspace / "web" / "index.html")
        i18n_js = _crlf_pin(workspace / "web" / "src" / "core" / "i18n.js")
        docs = _doc_pointers(workspace, force_refresh=force_refresh)
    except Exception as exc:  # noqa: BLE001 - the sentinel reports, never panics
        return {
            "live": False,
            "error": f"{type(exc).__name__}: {exc}",
            "generated_at": utc_stamp(),
            "honest_limits": [
                "full test suite not run here; CI is the authority on the suite",
                "the sentinel cannot testify to a red it has not seen; a check that cannot run reports rc != 0 / live=False, never a guess",
            ],
        }
    body = {
        "live": True,
        "generated_at": utc_stamp(),
        "head_live": head_live,
        "fact_pack": pack,
        "commits_ahead": ahead,
        "in_sync": (None if ahead is None else ahead <= 1),
        "crlf_pins": {"index_html": index_html, "i18n_js": i18n_js},
        "crlf_ok": bool(index_html["ok"] and i18n_js["ok"]),
        "doc_pointers": docs,
        "honest_limits": [
            "full test suite not run here; CI is the authority on the suite",
            "in_sync tolerates exactly the fact-pack commit itself; commits_ahead is None (not red) when this clone cannot see the pack's head object — a shallow CI checkout (fetch-depth=1) is the usual cause; commits_ahead > 1 means the pack is behind HEAD by more than its own commit — the push pipeline has not run, or this clone holds commits the remote has not seen",
            "doc_pointers rides a background thread; the panel shows 'running' until it lands (cached result served for 10 minutes after); the refresh button forces a synchronous pass capped at 90s",
        ],
    }
    return body
